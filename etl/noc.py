def _ok(noc):
    return bool(noc) and len(noc) == 5 and noc[0].isdigit()


def teer_of(noc):
    return int(noc[1]) if _ok(noc) and noc[1].isdigit() else None


def broad_of(noc):
    return BROAD.get(noc[0], "未分类") if _ok(noc) else "未分类"


def mid_of(noc):
    if not _ok(noc):
        return "未分类"
    if noc in NOC_INFO:
        return NOC_INFO[noc][0]
    for pat, name in MID_PREFIX:
        if re.match(pat, noc):
            return name
    return broad_of(noc)


def fine_of(noc):
    if not _ok(noc):
        return "未分类"
    return NOC_INFO[noc][1] if noc in NOC_INFO else mid_of(noc)


def classify(noc):
    """noc → {teer, broad, mid, fine}(供 mart 写到 job 上 + 建 noc 维度)。"""
    t = teer_of(noc)
    return {
        "teer": t, "teerLabel": f"TEER {t}" if t is not None else "未分类",
        "broad": broad_of(noc), "mid": mid_of(noc), "fine": fine_of(noc),
    }
