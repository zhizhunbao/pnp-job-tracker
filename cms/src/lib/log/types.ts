/**
 * 写一行日志要的两样。
 */
export type LogIn = {
  /**
   * 来源标签,不带方括号,`log()` 会补上。
   */
  tag: string

  /**
   * 正文。字面量从下面各域的表里取,代码只负责拼变量。
   */
  text: string
}

/**
 * 写日志没有返回值。
 */
export type LogOut = void
