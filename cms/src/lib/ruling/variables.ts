/**
 * 判定域的**运行时状态** —— 域里唯一可以放变量的地方。
 *
 * 🔴 **为什么单独一格**:`constants.ts` 装的是 JSON 装得下的死值,`types.ts` 装形状,
 * 两个都装不下「会变的东西」。而缓存的本质就是状态,`functions.ts` 顶层又只许有 `function`
 * —— 没有这一格,状态就只能靠 `eslint-disable` 赖在函数堆里,理由散在各处没人管。
 * 摆成一个文件,**这个域一共有多少可变状态,一眼数得清**。
 *
 * 🔴 **为什么是一个容器对象,不是几个 `export let`**:`export let` 跨模块是**只读活绑定**,
 * 别的文件里 `tables = …` 会当场编译错。改属性才是合法的写法,顺带也逼着每一处写明
 * 「我在改哪一格状态」。
 *
 * 🔴 **缓存必须是跨路由单件**:每个 route 模块各存一份 = 两倍的整库扫描。
 * 详情页是全站流量最大的页,判定底表禁每请求现算(prod-pool-wedge 教训)。
 * TTL 到点重取;Render 单实例,重启即失效。
 *
 * @author Frank
 * @time 2026-08-20 20:15:00
 */

import type { RulingCache } from './types'

/**
 * 判定域全部的可变状态,就这两格。
 */
export const CACHE: RulingCache = {
  /**
   * 六张判定底表那一份。**开机是空的** —— 第一次取的人负责灌,之后按 TTL 重取。
   */
  tables: null,

  /**
   * 指定雇主名录按省的那几份。开机是空的,按省逐个填。
   */
  byProvince: new Map(),
}
