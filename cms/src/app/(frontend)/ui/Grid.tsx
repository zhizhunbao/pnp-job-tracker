'use client'
// 事实网格:**一批**标签-值排成 N 列,列宽跨行对齐(前 cols-1 列 max-content,末列吃剩余宽)。
// 用法:cols=列数,children 按行铺平(每行 cols 个格);格子自己就是网格项。
// 铁律:一行里有多个事实就拆成列,别塞进一句话(那正是「废话多」的来源)。
// 基准=本省抽选卡的四列 grid(Frank 2026-07-26 走查:「都像最后一个卡片一样排列组合,每列都左对齐」)。
//
// ── 与两个近邻的分界(2026-08-17 Frank 两次点破,写在这免得再合错)──────────────
// ① **不是 Row**(ui/Row):那个渲**一条**事实,标签宽写死 88 是**全站约定** ——
//    正因为写死,散在几十处的 Row 才能上下对齐成一条竖线。这里的列宽是**这一批数据**
//    自己算出来的,换一批就换一个宽度。两种对齐策略互斥:合成一个组件,就得同时支持
//    「我是一条」和「我是一批」两种调用姿势,那是个坏 API。两件各自成件,并排住在 ui/。
// ② **不是 CardKV**(ui/Card):那个的网格列装的是**条目**(k 在 v 上方,一行两个条目),
//    是卡片的一个部位;这里的网格列装的是**格子**(k 与 v 是同一行相邻两格)。
//    两者都用 display:grid、都渲 k/v —— 但那是实现相同,不是同一件事。
//
// 单元格的角色类 gridK(标签)/ gridV(值)/ gridN(注)由调用方按格写,组件不按列位自动派:
// 同一列在不同行里角色可以不同(薪资表首行是表头,整行走 gridN),按列位派一半场合是错的。
// 三个类的值在 main.css 第 12 段;曾经有 FG_K/FG_V/FG_N 三个字符串别名常量,
// 值搬进 CSS 之后它们只剩一层跳转,2026-08-17 一并删掉,调用点直接写字面类名。
import React from 'react'

export function Grid({ cols, children }: { cols: number; children: React.ReactNode }) {
  return (
    <div className="grid" style={{ '--gc': cols - 1 } as React.CSSProperties}>
      {children}
    </div>
  )
}
