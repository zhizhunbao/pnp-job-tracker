/**
 * 冷门职业名的按码补全缓存。**必须挂在模块级**:写在组件体内的话每次渲染重建一个空对象,
 * 既缓存不到东西,又会让「拿不到名字」的码永远进不了已办清单 —— 配上以名字表为依赖的
 * effect 就是死循环(名字查不到 → 造新对象 → 依赖变 → 再查),浏览器持续轰 /api/quiz。
 */
export const CACHE = {
  /**
   * 查到的名字,键 = `<语言>:<职业码>`;5 分钟不过期 —— 职业名不会变,一次页面生命周期里
   * 查到就一直有效。
   */
  titles: {} as Record<string, string>,

  /**
   * 已经问过的码(不论问到没问到),键同上。失败不重试:同一个码问一次拿不到名字,
   * 再问十次也一样。「问过没问过」记在这儿而不看名字表 —— 查不到名字的码不会写进名字表,
   * 拿它当判据的话这个码每轮都还在待办里,而每次又造新对象,就转不出来了。
   */
  tried: new Set<string>(),
}
