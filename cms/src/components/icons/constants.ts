/**
 * 图标尺寸:1em = 跟随所在文字的字号(全站图标不定绝对像素 —— 图标是文字的一部分,
 * 字大它就大;调用点要改尺寸传 size 覆写)。
 */
export const ICON_SIZE = '1em'

/**
 * 全屏钮两态图标的落地边长(px):图标画在 24×24 的坐标系里(见 MAXICON_VIEW_BOX),
 * 到界面上按这个数缩放。它**不跟 ICON_SIZE 走 1em** —— 那枚是随文字长大的行内图标,
 * 而这枚长在弹框标题栏的方钮里,钮宽是定死的,跟着标题字号变会把钮撑歪。
 * 写成字符串是因为它直接进 svg 的 width/height 属性,属性值本来就是字符串。
 */
export const MAXICON_SIZE_PX = '14'

/**
 * 两态图标的画布坐标系:左上角 (0,0)、24 格见方。lucide 全家用的就是这个格子,
 * 手画件跟着用,两套图标的线宽与留白才对得上 —— 换成别的数,同样的笔画会画歪。
 */
export const MAXICON_VIEW_BOX = '0 0 24 24'

/**
 * 不填充:这是线条图标,形状全靠描边画出来。
 * 不写这一格会吃 svg 自己的默认填充(黑),两个折角会被当成闭合三角涂成黑块。
 */
export const MAXICON_FILL = 'none'

/**
 * 描边取当前文字颜色:图标是钮上文字的一部分,钮换色(hover、禁用)时它自己跟着换,
 * 不必为每种态各写一份颜色 —— 与 lucide 那套的 stroke 口径一致。
 */
export const MAXICON_STROKE = 'currentColor'

/**
 * 线宽,量在 24 格坐标系里:比 lucide 默认的 2 略粗 ——
 * 这枚图标落地只有 14px,线再细在手机上会糊成一个灰点。
 */
export const MAXICON_STROKE_WIDTH = '2.2'

/**
 * 线端画圆头,不用默认的平头:两枚图标各四笔(两个折角 + 两根斜杆)都是断开的短线,
 * 平头的切口在 14px 下看起来像被削掉一角。
 */
export const MAXICON_LINE_CAP = 'round'

/**
 * 转角画圆角:两个折角(每个箭头的头)各有一个拐点,取默认的尖角时
 * 2.2 的线宽会在拐点甩出一根刺;斜杆没有拐点,这一格只为那两个折角写。
 */
export const MAXICON_LINE_JOIN = 'round'

/**
 * 还原态的笔画(`MaxIcon` 在 maximized=true 时画它):一个 `d` 串装四条子路径,
 * 坐标全量在 24 格坐标系里 —— `M` 抬笔移到某点,`h`/`v` 画相对横竖,`l` 画相对斜线。
 * 拆开是**两个箭头**不是四个:前两笔是折角(箭头的头),顶点落在近中心的
 * (10,14) 与 (14,10);后两笔从这两个顶点斜拉到画布的左下角 (3,21) 与右上角 (21,3) 当杆。
 * 头在里、杆在外 = 两个箭头朝内指向中心 = 点它退出全屏。
 */
export const MAXICON_RESTORE_PATH = 'M4 14h6v6M20 10h-6V4M14 10l7-7M10 14l-7 7'

/**
 * 全屏态的笔画(`MaxIcon` 在 maximized=false 时画它):写法与 MAXICON_RESTORE_PATH 同一套,
 * 四条子路径拼成**两个箭头**,方向整个反过来:折角顶点这回落在画布的右上角 (21,3)
 * 与左下角 (3,21),斜杆从这两个角往中心的 (14,10) / (10,14) 收。
 * 头在外、杆在里 = 两个箭头朝外顶向那条对角 = 点它进入全屏。
 * 只顶这两个角、不是四角 —— 这枚与还原态是同一条对角线上的一对。
 */
export const MAXICON_ENTER_PATH = 'M15 3h6v6M9 21H3v-6M21 3l-7 7M3 21l7-7'
